from e2e.helpers import unique_name


def test_add_spare_part_and_low_stock_threshold(page, base_url):
    low_name, normal_name = unique_name("LowStockPart"), unique_name("NormalStockPart")
    page.goto(base_url, wait_until="networkidle")
    page.locator('[data-page="parts"]').click()
    before = int(page.locator(".card-heading p").inner_text().split()[0])
    page.get_by_role("button", name="Add part").click()
    dialog = page.get_by_role("dialog", name="Add spare part")
    dialog.locator('input[name="name"]').fill(low_name)
    dialog.locator('input[name="stock"]').fill("2")
    dialog.locator('input[name="unitPrice"]').fill("3900")
    dialog.get_by_role("button", name="Add part").click()
    low_row = page.get_by_role("row").filter(has_text=low_name)
    low_row.wait_for()
    low_id = low_row.locator("td").nth(1).inner_text()
    assert low_id.startswith("PT-")
    low_row.get_by_text("Low stock", exact=True).wait_for()
    assert low_row.get_by_text("3,900 ₸", exact=True).is_visible()
    page.get_by_role("button", name="Add part").click()
    dialog = page.get_by_role("dialog", name="Add spare part")
    dialog.locator('input[name="name"]').fill(normal_name)
    dialog.locator('input[name="stock"]').fill("3")
    dialog.locator('input[name="unitPrice"]').fill("4100")
    dialog.get_by_role("button", name="Add part").click()
    normal_row = page.get_by_role("row").filter(has_text=normal_name)
    normal_row.wait_for()
    normal_row.get_by_text("In stock", exact=True).wait_for()
    assert page.get_by_text(f"{before + 2} types of parts in stock", exact=True).is_visible()
